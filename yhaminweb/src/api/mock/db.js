function flatDept(tree, out = [], path = "") {
  tree.forEach((n) => {
    const p = path ? `${path} / ${n.label}` : n.label;
    n.deptPath = p;
    out.push(n);
    if (n.children?.length) flatDept(n.children, out, p);
  });
  return out;
}
